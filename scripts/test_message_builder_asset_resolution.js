            const hook = { write: null, failOpen: false };
            const origOpen = idb.open;
            idb.open = function (name, version) {
                if (hook.failOpen) throw new Error('P2.4 rig: open refused');
                const req = origOpen.call(idb, name, version);
                let rawDb = null;
                Object.defineProperty(req, 'result', {
                    configurable: true, enumerable: true,
                    get: function () {
                        if (!rawDb) return null;
                        if (!rawDb.__p24) {
                            const origTx = rawDb.transaction.bind(rawDb);
                            rawDb.transaction = function (storeName, mode) {
                                const tx = origTx(storeName, mode);
                                const origOS = tx.objectStore.bind(tx);
                                tx.objectStore = function (osName) {
                                    const os = origOS(osName);
                                    const abortLikeRealOne = () => {
                                        tx.__pending++;
                                        setTimeout(function () {
                                            tx.__pending--;
                                            if (tx.onabort) tx.onabort({ target: tx });
                                            else if (tx.onerror) tx.onerror({ target: tx });
                                        }, 0);
                                        return { result: undefined, error: null, onsuccess: null, onerror: null };
                                    };
                                    return {
                                        get: function (k) { return os.get(k); },
                                        getAll: function () { return os.getAll(); },
                                        put: function (value, key) {
                                            if (hook.write && hook.write(osName, key)) return abortLikeRealOne();
                                            return os.put(value, key);
                                        },
                                        delete: function (key) {
                                            if (hook.write && hook.write(osName, key)) return abortLikeRealOne();
                                            return os.delete(key);
                                        },
                                    };
                                };
                                return tx;
                            };
                            rawDb.__p24 = true;
                        }
                        return rawDb;
                    },
                    set: function (v) { rawDb = v; },
                });
                return req;
            };
